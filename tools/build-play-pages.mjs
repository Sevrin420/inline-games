// Builds games/<game>/play/index.html from games/<game>/index.html (no hand copy).
//
// Why: X player cards that play (Tweetcraft, levelsio's Quake) post one URL
// (the card page) and point twitter:player at a SEPARATE game page. The play
// page is the same game file with three additions:
//   1. <base href="/<game>/"> so relative assets (hens/, ../shared/) resolve
//      exactly as they do from /<game>/
//   2. twitter:player pointing at itself, plus robots noindex
//   3. a small "Play in new tab" link, shown only when framed (the desktop card)
//
// Run by .github/workflows/deploy-games.yml before the rsync, and by the
// browser test. The output is gitignored: edit games/<game>/index.html instead.
//   node tools/build-play-pages.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ORIGIN = 'https://membersonly.cc';
const GAMES = ['coop-sweep'];
const gamesDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'games');

function once(html, needle, replacement, game) {
  const n = html.split(needle).length - 1;
  if (n !== 1) throw new Error(`${game}: expected exactly one ${JSON.stringify(needle)}, found ${n}`);
  return html.replace(needle, replacement);
}

for (const game of GAMES) {
  const src = path.join(gamesDir, game, 'index.html');
  let html = fs.readFileSync(src, 'utf8');
  const full = `${ORIGIN}/${game}/`;

  html = once(html, '<!doctype html>\n',
    `<!doctype html>\n<!-- GENERATED by tools/build-play-pages.mjs from games/${game}/index.html at deploy time. Do not edit. -->\n`, game);
  html = once(html, '<head>\n', `<head>\n<base href="/${game}/">\n<meta name="robots" content="noindex">\n`, game);
  html = once(html, `<meta name="twitter:player" content="${full}">`,
    `<meta name="twitter:player" content="${full}play/">`, game);
  html = once(html, '</body>', `<!-- Framed (the X player card on desktop): offer the full page in a new tab. -->
<style>#mo-newtab{position:fixed;top:3px;right:4px;z-index:2147483001;font:600 10px/1 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:rgba(255,253,244,.94);color:#2a1a10;border:1.5px solid #2a1a10;border-radius:999px;padding:3px 7px;text-decoration:none;box-shadow:0 1px 0 rgba(0,0,0,.25);-webkit-tap-highlight-color:transparent}</style>
<script>
(function () {
  var framed; try { framed = window.top !== window; } catch (e) { framed = true; }
  if (!framed || /[?&]shot\\b/.test(location.search)) return;
  var a = document.createElement('a');
  a.id = 'mo-newtab'; a.href = ${JSON.stringify(full)}; a.target = '_blank'; a.rel = 'noopener';
  a.textContent = 'Play in new tab \\u2197';
  document.body.appendChild(a);
})();
</script>
</body>`, game);

  const outDir = path.join(gamesDir, game, 'play');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), html);
  console.log(`built ${path.relative(path.join(gamesDir, '..'), path.join(outDir, 'index.html'))}`);
}
